"""
Large synthetic dataset (5,000 documents) loaded into all three containers.

The quantizedFlat and diskANN vector indexes need a minimum number of vectors
(about 1,000) before they build their compressed / graph structures. Below that
threshold Cosmos DB falls back to a full scan. This module creates 5,000 support
tickets with
REAL embeddings generated by an Azure OpenAI embedding model deployed in
Microsoft Foundry. The flat container receives the same documents so the RU
cost of an exact full scan can be compared at the same scale.

Environment variables:
    AZURE_OPENAI_ENDPOINT              e.g. https://<resource>.openai.azure.com/
    AZURE_OPENAI_EMBEDDING_DEPLOYMENT  deployment name (default: text-embedding-3-small)
    AZURE_OPENAI_API_KEY               optional; if not set, Entra ID is used
                                       (requires the "Cognitive Services OpenAI User" role)
    AZURE_OPENAI_API_VERSION           optional (default: 2024-10-21)

The generated dataset is cached in large_vectors.json so the embeddings are
only computed once. Run this file directly to pre-generate it:

    python large_dataset.py
"""
import json
import os
import random

from generate_sample_data import CATEGORIES, fill_template

LARGE_DATASET_FILE = os.path.join(os.path.dirname(__file__), "large_vectors.json")
LARGE_DOCUMENT_COUNT = 5000
EMBEDDING_DIMENSIONS = 256  # Must match the vector embedding policy of the containers
EMBEDDING_BATCH_SIZE = 200

# Openers and closers add variety so the 5,000 tickets are not near-duplicates
OPENERS = [
    "", "", "Hi team, ", "Hello, ", "Urgent: ", "Good morning. ", "Hi support, ",
    "Second time contacting you about this. ", "Quick question. ", "Please help! ",
]
CLOSERS = [
    "", "", " Thanks in advance.", " This is very frustrating.", " Please advise.",
    " I need this resolved today.", " Let me know if you need more details.",
    " My customer number is {customer_id}.", " I'm considering cancelling my plan.",
    " Any help is appreciated.",
]

# Semantic queries: embedded with the same model as the documents
SEMANTIC_QUERIES = [
    {"id": "semantic-login-issue", "description": "I can't login to my account"},
    {"id": "semantic-double-charge", "description": "My payment was charged twice"},
    {"id": "semantic-missing-package", "description": "Package hasn't arrived yet"},
    {"id": "semantic-account-security", "description": "Protect my account from hackers"},
    {"id": "semantic-product-broken", "description": "My product stopped working"},
    {"id": "semantic-refund-request", "description": "I need a refund for my order"},
    {"id": "semantic-app-crash", "description": "The mobile app keeps crashing"},
    {"id": "semantic-change-address", "description": "Update my shipping address"},
    {"id": "semantic-battery-life", "description": "Battery drains much faster than advertised"},
    {"id": "semantic-delete-data", "description": "Delete all my personal data (GDPR)"},
]


def get_embedding_client():
    """Create an Azure OpenAI client using an API key or Entra ID."""
    from openai import AzureOpenAI

    endpoint = os.environ.get("AZURE_OPENAI_ENDPOINT")
    if not endpoint:
        raise ValueError(
            "AZURE_OPENAI_ENDPOINT must be set to the endpoint of your Foundry / "
            "Azure OpenAI resource (and AZURE_OPENAI_EMBEDDING_DEPLOYMENT to the deployment name)."
        )

    api_version = os.environ.get("AZURE_OPENAI_API_VERSION", "2024-10-21")
    api_key = os.environ.get("AZURE_OPENAI_API_KEY")

    if api_key:
        return AzureOpenAI(azure_endpoint=endpoint, api_key=api_key, api_version=api_version)

    from azure.identity import DefaultAzureCredential, get_bearer_token_provider
    token_provider = get_bearer_token_provider(
        DefaultAzureCredential(), "https://cognitiveservices.azure.com/.default"
    )
    return AzureOpenAI(
        azure_endpoint=endpoint,
        azure_ad_token_provider=token_provider,
        api_version=api_version,
    )


def embed_texts(texts: list) -> list:
    """Generate 256-dimensional embeddings for a list of texts, in batches."""
    client = get_embedding_client()
    deployment = os.environ.get("AZURE_OPENAI_EMBEDDING_DEPLOYMENT", "text-embedding-3-small")

    embeddings = []
    for start in range(0, len(texts), EMBEDDING_BATCH_SIZE):
        batch = texts[start:start + EMBEDDING_BATCH_SIZE]
        # text-embedding-3-* models support shortening the vector with `dimensions`
        response = client.embeddings.create(
            model=deployment,
            input=batch,
            dimensions=EMBEDDING_DIMENSIONS,
        )
        embeddings.extend(
            [round(v, 6) for v in item.embedding]
            for item in sorted(response.data, key=lambda d: d.index)
        )
        print(f"  Embedded {min(start + EMBEDDING_BATCH_SIZE, len(texts))}/{len(texts)}", flush=True)

    return embeddings


def generate_large_documents(count: int = LARGE_DOCUMENT_COUNT, seed: int = 42) -> list:
    """Generate synthetic support tickets (without embeddings)."""
    random.seed(seed)
    categories = list(CATEGORIES.keys())
    documents = []
    seen_contents = set()

    for i in range(count):
        category = categories[i % len(categories)]
        cat_data = CATEGORIES[category]

        priority = random.choices(
            list(cat_data["priority_weights"].keys()),
            weights=list(cat_data["priority_weights"].values())
        )[0]
        tags = random.sample(cat_data["tags_pool"], k=random.randint(2, 4))

        # Retry until the text is unique: identical texts would get identical
        # embeddings and show up as duplicated results in the vector search
        while True:
            body = fill_template(random.choice(cat_data["templates"]), category)
            closer = random.choice(CLOSERS).replace("{customer_id}", f"C-{random.randint(10000, 99999)}")
            content = f"{random.choice(OPENERS)}{body}{closer}"
            if content not in seen_contents:
                seen_contents.add(content)
                break

        doc_num = (i // len(categories)) + 1
        document_id = f"large-{category}-{doc_num:04d}"

        documents.append({
            "document_id": document_id,
            "chunk_id": f"{document_id}-chunk-0",
            "content": content,
            "metadata": {
                "source": "synthetic-large",
                "category": category,
                "priority": priority,
                "tags": tags,
                "chunkIndex": 0
            }
        })

    return documents


def build_large_dataset(count: int = LARGE_DOCUMENT_COUNT) -> dict:
    """Generate documents and queries and compute their embeddings with Azure OpenAI."""
    print(f"Generating {count} synthetic support tickets...", flush=True)
    documents = generate_large_documents(count)

    print("Generating document embeddings with Azure OpenAI...", flush=True)
    for doc, embedding in zip(documents, embed_texts([d["content"] for d in documents])):
        doc["embedding"] = embedding

    print("Generating query embeddings...", flush=True)
    queries = [
        {**q, "embedding": emb}
        for q, emb in zip(SEMANTIC_QUERIES, embed_texts([q["description"] for q in SEMANTIC_QUERIES]))
    ]

    return {"documents": documents, "queries": queries}


def load_large_dataset(create_if_missing: bool = True) -> dict:
    """Load the cached dataset, generating (and caching) it if it does not exist yet."""
    if os.path.exists(LARGE_DATASET_FILE):
        with open(LARGE_DATASET_FILE, "r") as f:
            return json.load(f)

    if not create_if_missing:
        return {"documents": [], "queries": []}

    data = build_large_dataset()
    with open(LARGE_DATASET_FILE, "w") as f:
        json.dump(data, f)
    print(f"Saved {len(data['documents'])} documents to {LARGE_DATASET_FILE}", flush=True)
    return data


if __name__ == "__main__":
    dataset = load_large_dataset()
    print(f"Dataset ready: {len(dataset['documents'])} documents, {len(dataset['queries'])} queries")
